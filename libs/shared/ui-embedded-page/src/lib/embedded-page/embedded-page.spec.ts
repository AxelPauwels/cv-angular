import { Component } from '@angular/core';
import { TestBed } from '@angular/core/testing';
import { provideHttpClient } from '@angular/common/http';
import {
  HttpTestingController,
  provideHttpClientTesting,
} from '@angular/common/http/testing';
import { FormatSimple, provideTolgee, Tolgee } from '@tolgee/ngx';
import { LOADING_DELAY_MS } from '@cv/shared-util-loading';
import { EmbeddedPage } from './embedded-page';

@Component({
  imports: [EmbeddedPage],
  template: `<ds-embedded-page
    src="//evil.example/report.html"
    title="t.heading.code-coverage" />`,
})
class CrossOriginHost {}

// a ui lib can't use data-access-i18n: only the texts these tests read
const i18n = () =>
  provideTolgee(() =>
    Tolgee()
      .use(FormatSimple())
      .init({
        language: 'en',
        staticData: {
          en: {
            't.embedded-page.not-available':
              'This report is not available here. It is generated by the production build (<code>npm run build:production</code>).',
            't.embedded-page.loading': 'Loading the report',
          },
        },
      })
  );

describe('EmbeddedPage', () => {
  async function render(answer: (http: HttpTestingController) => void) {
    TestBed.configureTestingModule({
      providers: [provideHttpClient(), provideHttpClientTesting(), i18n()],
    });
    const fixture = TestBed.createComponent(EmbeddedPage);
    fixture.componentRef.setInput('src', '/coverage/index.html');
    fixture.componentRef.setInput('title', 't.heading.code-coverage');
    fixture.detectChanges();
    TestBed.tick();

    answer(TestBed.inject(HttpTestingController));
    await fixture.whenStable();
    return fixture;
  }

  it('shows an existing page in an iframe', async () => {
    // Arrange
    const answer = (http: HttpTestingController) =>
      http.expectOne('/coverage/index.html').flush('<html>coverage</html>');

    // Act
    const element = (await render(answer)).nativeElement as HTMLElement;

    // Assert
    // the same page title as every content page, no card around the report
    expect(element.querySelector('ds-page-title h1')?.textContent?.trim()).toBe(
      't.heading.code-coverage'
    );
    expect(element.querySelector('mat-card')).toBeNull();
    const frame = element.querySelector('iframe');
    expect(frame?.getAttribute('src')).toBe('/coverage/index.html');
    expect(frame?.title).toBe('t.heading.code-coverage');
    // a button opens the same page in a new browser tab
    const open = element.querySelector('a[matButton]');
    expect(open?.getAttribute('href')).toBe('/coverage/index.html');
    expect(open?.getAttribute('target')).toBe('_blank');
    expect(open?.querySelector('mat-icon')?.textContent?.trim()).toBe(
      'open_in_new'
    );
  });

  it('shows a message instead of the app nested in itself', async () => {
    // Arrange
    const answer = (http: HttpTestingController) =>
      http
        .expectOne('/coverage/index.html')
        .flush('<html><body><app-root></app-root></body></html>');

    // Act
    const element = (await render(answer)).nativeElement as HTMLElement;

    // Assert
    expect(element.querySelector('iframe')).toBeNull();
    expect(element.textContent).toContain('not available');
  });

  it('shows a message when the page is missing', async () => {
    // Arrange
    const answer = (http: HttpTestingController) =>
      http
        .expectOne('/coverage/index.html')
        .flush('', { status: 404, statusText: 'Not Found' });

    // Act
    const element = (await render(answer)).nativeElement as HTMLElement;

    // Assert
    expect(element.querySelector('iframe')).toBeNull();
    expect(element.textContent).toContain('not available');
  });

  it('shows a labelled progress bar while a slow page loads', async () => {
    // Arrange
    TestBed.configureTestingModule({
      providers: [provideHttpClient(), provideHttpClientTesting(), i18n()],
    });
    const fixture = TestBed.createComponent(EmbeddedPage);
    fixture.componentRef.setInput('src', '/coverage/index.html');
    fixture.componentRef.setInput('title', 't.heading.code-coverage');
    fixture.detectChanges();
    TestBed.tick();
    TestBed.inject(HttpTestingController).expectOne('/coverage/index.html');

    // Act: the request stays unanswered (whenStable would wait for it)
    await new Promise((resolve) => setTimeout(resolve, LOADING_DELAY_MS + 50));
    fixture.detectChanges();

    // Assert
    const element = fixture.nativeElement as HTMLElement;
    await vi.waitFor(() => {
      fixture.detectChanges();
      expect(
        element.querySelector('mat-progress-bar')?.getAttribute('aria-label')
      ).toBe('Loading the report');
    });
    expect(element.querySelector('iframe')).toBeNull();
  });

  it('never loads a page from another origin', async () => {
    // Arrange
    TestBed.configureTestingModule({
      providers: [provideHttpClient(), provideHttpClientTesting(), i18n()],
    });
    const fixture = TestBed.createComponent(CrossOriginHost);

    // Act
    fixture.detectChanges();
    TestBed.tick();
    await fixture.whenStable();

    // Assert
    TestBed.inject(HttpTestingController).verify();
    const element = fixture.nativeElement as HTMLElement;
    expect(element.querySelector('iframe')).toBeNull();
    expect(element.textContent).toContain('not available');
  });

  it('styles the page again when the theme or font changes on <html>', async () => {
    // Arrange
    const applyFont = vi.spyOn(
      EmbeddedPage.prototype as unknown as { applyFont(): void },
      'applyFont'
    );
    const answer = (http: HttpTestingController) =>
      http.expectOne('/coverage/index.html').flush('<html>coverage</html>');
    await render(answer);
    const calls = applyFont.mock.calls.length;

    // Act
    document.documentElement.setAttribute('data-test-theme', 'fire');

    // Assert
    await vi.waitFor(() =>
      expect(applyFont.mock.calls.length).toBeGreaterThan(calls)
    );
    document.documentElement.removeAttribute('data-test-theme');
    applyFont.mockRestore();
  });
});
